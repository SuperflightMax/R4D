def clip_x(poly,boundary,keep_left):
    out=[]
    for a,b in zip(poly[-1:]+poly[:-1],poly):
        ia=a[0]<=boundary if keep_left else a[0]>=boundary
        ib=b[0]<=boundary if keep_left else b[0]>=boundary
        if ia!=ib:
            t=(boundary-a[0])/(b[0]-a[0]);out.append([boundary,round(a[1]+t*(b[1]-a[1]),4)])
        if ib:out.append(b)
    return out

